import { createHash } from 'crypto';

/** Deterministic UUID (v4-shaped) from a seed key, so re-running the seed is idempotent. */
export function seedId(key: string): string {
  const h = createHash('sha256').update(`rove-seed:${key}`).digest('hex');
  const variant = ((parseInt(h[16], 16) & 0x3) | 0x8).toString(16);
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-${variant}${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

const REF = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';
export function seedReference(key: string): string {
  const h = createHash('sha256').update(`rove-ref:${key}`).digest();
  let s = 'RV-';
  for (let i = 0; i < 6; i++) s += REF[h[i] % REF.length];
  return s;
}

