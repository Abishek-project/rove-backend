import { existsSync, readFileSync } from 'fs';
import { join, resolve } from 'path';
import sharp from 'sharp';

/** Real (Unsplash) vehicle photos declared in seed-assets/vehicles/manifest.json. */
export const PHOTO_DIR = resolve(__dirname, '../../seed-assets/vehicles');

export interface PhotoCredit {
  file: string;
  photoUrl: string;
  photographer: string;
  /** Optional: Unsplash profile pages are bot-protected, so the photo page URL is the primary credit link. */
  photographerUrl?: string;
}

export interface Manifest {
  vehicles: Record<string, PhotoCredit[]>;
}

const PHOTO_URL = /^https:\/\/unsplash\.com\/photos\/[A-Za-z0-9_-]+\/?$/;
const PROFILE_URL = /^https:\/\/unsplash\.com\/@[A-Za-z0-9_.-]+\/?$/;

/** Loads and validates the manifest. Rejects anything that is not a free-licence Unsplash photo. */
export function loadManifest(): Manifest {
  const path = join(PHOTO_DIR, 'manifest.json');
  if (!existsSync(path)) return { vehicles: {} };
  const raw = JSON.parse(readFileSync(path, 'utf8')) as Partial<Manifest>;
  const vehicles = raw.vehicles ?? {};
  const problems: string[] = [];
  for (const [key, photos] of Object.entries(vehicles)) {
    for (const p of photos) {
      const where = `${key}/${p.file}`;
      if (!p.file || /[\\/]/.test(p.file)) problems.push(`${where}: invalid file name`);
      else if (!existsSync(join(PHOTO_DIR, p.file))) problems.push(`${where}: file not found in seed-assets/vehicles/`);
      if (/plus\.unsplash\.com/i.test(p.photoUrl ?? '') || !PHOTO_URL.test(p.photoUrl ?? '')) {
        problems.push(`${where}: photoUrl must be a free-licence https://unsplash.com/photos/… page (no Unsplash+)`);
      }
      if (!p.photographer?.trim()) problems.push(`${where}: photographer is required`);
      if (p.photographerUrl !== undefined && !PROFILE_URL.test(p.photographerUrl))
        problems.push(`${where}: photographerUrl, when given, must be https://unsplash.com/@…`);
    }
  }
  if (problems.length) throw new Error(`Invalid seed photo manifest:\n  - ${problems.join('\n  - ')}`);
  return { vehicles };
}

export interface SeedImage {
  key: string;
  buffer: Buffer;
  width: number;
  height: number;
}

/** JPEG buffers for a vehicle's manifest photos, or null when it has none. */
export async function photosFor(manifest: Manifest, vehicleKey: string): Promise<SeedImage[] | null> {
  const entries = manifest.vehicles[vehicleKey];
  if (!entries?.length) return null;
  const out: SeedImage[] = [];
  for (const e of entries) {
    const input = readFileSync(join(PHOTO_DIR, e.file));
    const img = sharp(input).rotate();
    const meta = await img.metadata();
    // Normalise to a web-friendly JPEG ≤ 1600 px wide (keeps the bucket's 10 MB limit comfortably).
    const buffer = await img
      .resize({ width: Math.min(meta.width ?? 1600, 1600), withoutEnlargement: true })
      .jpeg({ quality: 82, mozjpeg: true })
      .toBuffer();
    const { width = 0, height = 0 } = await sharp(buffer).metadata();
    out.push({ key: `photo:${out.length}:${e.file}`, buffer, width, height });
  }
  return out;
}

/** Markdown credits for every manifest photo. */
export function creditsMarkdown(manifest: Manifest, labels: Record<string, string>): string {
  const lines = [
    '# Seed photo credits',
    '',
    'Vehicle photos used by `npm run seed`, all from [Unsplash](https://unsplash.com) under the',
    '[Unsplash License](https://unsplash.com/license) (free; no Unsplash+ images). Generated by `npm run seed:credits`.',
    '',
  ];
  const keys = Object.keys(manifest.vehicles).filter((k) => manifest.vehicles[k].length);
  if (keys.length === 0) {
    lines.push('_No photos yet — vehicles use locally generated illustrations._', '');
    return lines.join('\n');
  }
  lines.push('| Vehicle | File | Photo | Credit |', '|---|---|---|---|');
  for (const k of keys) {
    for (const p of manifest.vehicles[k]) {
      lines.push(
        `| ${labels[k] ?? k} | \`${p.file}\` | [Unsplash](${p.photoUrl}) | Photo by ${p.photographerUrl ? `[${p.photographer}](${p.photographerUrl})` : p.photographer} on Unsplash |`,
      );
    }
  }
  lines.push('');
  return lines.join('\n');
}
