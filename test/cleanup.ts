import { createClient } from '@supabase/supabase-js';
import { config } from 'dotenv';
import { resolve } from 'path';
import WebSocket from 'ws';
import { createKysely } from '../src/database/database';

/**
 * Removes everything the e2e suite creates (vehicles named "Test E2E …" and their bookings,
 * files and payouts) so the shared local dev database keeps only seed data.
 * Runs before (in case a previous run aborted) and after the suite.
 */
export default async function cleanup(): Promise<void> {
  config({ path: resolve(__dirname, '../.env'), quiet: true });
  const db = createKysely(process.env.DATABASE_URL as string, 2);
  const storage = createClient(process.env.SUPABASE_URL as string, process.env.SUPABASE_SERVICE_ROLE_KEY as string, {
    auth: { persistSession: false },
    realtime: { transport: WebSocket as never },
  }).storage;
  try {
    const vehicles = await db
      .selectFrom('vehicles')
      .select('id')
      .where((eb) => eb.or([eb('make', '=', 'Test'), eb('make', '=', 'Draft')]))
      .where((eb) =>
        eb.or([eb('model', 'like', 'E2E %'), eb('model', '=', 'Renamed'), eb('model', '=', 'Upload Test')]),
      )
      .execute();
    const ids = vehicles.map((v) => v.id);
    if (ids.length) {
      const bookings = await db.selectFrom('bookings').select('id').where('vehicle_id', 'in', ids).execute();
      const bookingIds = bookings.map((b) => b.id);
      const [images, docs, photos] = await Promise.all([
        db.selectFrom('vehicle_images').select('storage_path').where('vehicle_id', 'in', ids).execute(),
        db.selectFrom('vehicle_documents').select('storage_path').where('vehicle_id', 'in', ids).execute(),
        bookingIds.length
          ? db.selectFrom('evidence_photos').select('storage_path').where('booking_id', 'in', bookingIds).execute()
          : Promise.resolve([]),
      ]);
      if (bookingIds.length) {
        await db.deleteFrom('support_requests').where('booking_id', 'in', bookingIds).execute();
        await db.deleteFrom('bookings').where('id', 'in', bookingIds).execute();
      }
      await db.deleteFrom('vehicles').where('id', 'in', ids).execute();
      const rm = async (bucket: string, paths: string[]) => {
        for (let i = 0; i < paths.length; i += 100) await storage.from(bucket).remove(paths.slice(i, i + 100));
      };
      await rm(
        'car-images',
        images.map((i) => i.storage_path),
      );
      await rm(
        'verification-documents',
        docs.map((d) => d.storage_path),
      );
      await rm(
        'booking-evidence',
        photos.map((p) => p.storage_path),
      );
    }
    // Payouts generated by the suite no longer cover any booking once those are gone.
    await db
      .deleteFrom('payouts')
      .where((eb) =>
        eb.not(eb.exists(eb.selectFrom('bookings').select('id').whereRef('bookings.payout_id', '=', 'payouts.id'))),
      )
      .execute();
    await db.deleteFrom('support_requests').where('subject', '=', 'Help please').execute();
  } finally {
    await db.destroy();
  }
}
